/** An Arabic count: one, two, three to ten, and eleven on take different forms. */
const arCount = (count: number, digits: string, [one, two, few, many]: [string, string, string, string]) =>
  count === 1 ? one : count === 2 ? two : count >= 3 && count <= 10 ? `${digits} ${few}` : `${digits} ${many}`

